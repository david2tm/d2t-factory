export interface Run { x: number; y: number; w: number; key: string }

// A pixel map as horizontal runs of one color (fewer rects than pixels).
export function runs(rows: readonly string[]): Run[] {
  const out: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const key = row[x];
      let w = 1;
      while (x + w < row.length && row[x + w] === key) w++;
      if (key !== '.') out.push({ x, y, w, key });
      x += w;
    }
  });
  return out;
}

