// seat is 32×30), and the 9×9 glyphs. Drawn from the shared 20-color sprite palette only; each map
// row is one pixel row, one palette key per pixel ('.' is transparent). Frame 1 is base + `a`,
// frame 2 is base + `b`. Replaced wholesale when the final 32×32 art lands. Sprites are always
// rendered aria-hidden. Every agent role has a character (7-2); the CLI's run_check steps share one
// check-droid chassis (`droid`: a box body on treads, one photoreceptor, a status light).

